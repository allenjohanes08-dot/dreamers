export type Language = 'en' | 'sw';

export function getTranslation(lang: Language, section: keyof typeof translations.en, key: string, params?: Record<string, string | number>): string {
  const dictionary = translations[lang] || translations.en;
  const sectionObj = (dictionary as any)[section];
  if (!sectionObj) return String(key);
  
  let value = sectionObj[key];
  if (value === undefined) {
    // Fallback to english
    const enSection = (translations.en as any)[section];
    value = enSection ? enSection[key] : key;
  }
  
  if (typeof value === 'string' && params) {
    let result = value;
    for (const [paramKey, paramVal] of Object.entries(params)) {
      result = result.replace(`{${paramKey}}`, String(paramVal));
    }
    return result;
  }
  
  return String(value);
}
